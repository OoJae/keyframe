#!/usr/bin/env node
// Vendors packages/protocol/src/**/*.ts into a standalone consumer (default: plugin/src/protocol), which
// cannot take a workspace link (its own pnpm root and frozen lockfile). Deterministic: sorted traversal,
// fixed header, LF output, no timestamps. --check compares instead of writing and exits 1 on any drift.
//
//   node scripts/sync-protocol.mjs [--check] [--target <dir>]

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = "// GENERATED by scripts/sync-protocol.mjs - do not edit\n";
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(repoRoot, "packages", "protocol", "src");
const defaultTarget = path.join(repoRoot, "plugin", "src", "protocol");

function parseArgs(argv) {
  const opts = { check: false, target: defaultTarget };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") opts.check = true;
    else if (a === "--target") {
      const v = argv[++i];
      if (!v) throw new Error("--target needs a directory");
      opts.target = path.resolve(v);
    } else if (a.startsWith("--target=")) opts.target = path.resolve(a.slice("--target=".length));
    else if (a === "--help" || a === "-h") {
      console.log("usage: node scripts/sync-protocol.mjs [--check] [--target <dir>]");
      process.exit(0);
    } else throw new Error(`unknown argument: ${a}`);
  }
  return opts;
}

/** Relative POSIX paths of every *.ts file under dir, in byte order (locale-independent). */
async function listTs(dir) {
  let entries;
  try {
    entries = await readdir(dir, { recursive: true, withFileTypes: true });
  } catch (err) {
    if (err.code === "ENOENT") return [];
    throw err;
  }
  return entries
    .filter((e) => e.isFile() && e.name.endsWith(".ts"))
    .map((e) => path.relative(dir, path.join(e.parentPath, e.name)).split(path.sep).join("/"))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

async function expectedFiles() {
  const files = (await listTs(sourceDir)).filter((f) => !f.endsWith(".test.ts"));
  if (files.length === 0) throw new Error(`no sources found in ${sourceDir}`);
  const out = new Map();
  for (const rel of files) {
    const src = (await readFile(path.join(sourceDir, rel), "utf8")).replace(/\r\n/g, "\n");
    out.set(rel, HEADER + src);
  }
  return out;
}

async function main() {
  const { check, target } = parseArgs(process.argv.slice(2));
  if (path.resolve(target) === sourceDir || path.resolve(target).startsWith(sourceDir + path.sep)) {
    throw new Error("target must not be inside the protocol source directory");
  }
  const expected = await expectedFiles();
  const existing = await listTs(target);
  const problems = [];

  for (const [rel, content] of expected) {
    let current = null;
    try {
      current = await readFile(path.join(target, rel), "utf8");
    } catch (err) {
      if (err.code !== "ENOENT") throw err;
    }
    if (current === content) continue;
    problems.push(`${current === null ? "missing" : "differs"}: ${rel}`);
    if (!check) {
      await mkdir(path.dirname(path.join(target, rel)), { recursive: true });
      await writeFile(path.join(target, rel), content);
    }
  }

  for (const rel of existing) {
    if (expected.has(rel)) continue;
    problems.push(`stale: ${rel}`);
    if (check) continue;
    const content = await readFile(path.join(target, rel), "utf8");
    // Only ever delete files this script generated; anything else in the target is a human's and is an error.
    if (!content.startsWith(HEADER)) throw new Error(`refusing to delete non-generated file ${path.join(target, rel)}`);
    await rm(path.join(target, rel));
  }

  const where = path.relative(process.cwd(), target) || ".";
  if (check) {
    if (problems.length > 0) {
      console.error(`sync-protocol --check: ${where} is out of date (run pnpm sync:protocol):`);
      for (const p of problems) console.error(`  ${p}`);
      process.exit(1);
    }
    console.log(`sync-protocol --check: ${where} matches packages/protocol/src (${expected.size} files)`);
  } else {
    console.log(
      `sync-protocol: ${where} <- packages/protocol/src (${expected.size} files, ${problems.length} changed)`,
    );
  }
}

main().catch((err) => {
  console.error(`sync-protocol: ${err.message}`);
  process.exit(2);
});
