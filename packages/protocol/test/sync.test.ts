import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { PKG_ROOT, REPO_ROOT } from "./helpers.js";

const SCRIPT = path.join(REPO_ROOT, "scripts/sync-protocol.mjs");
const HEADER = "// GENERATED by scripts/sync-protocol.mjs - do not edit\n";
const target = mkdtempSync(path.join(tmpdir(), "kf-sync-"));
const run = (...args: string[]) =>
  spawnSync(process.execPath, [SCRIPT, "--target", target, ...args], { encoding: "utf8" });
const digest = () => {
  const h = createHash("sha256");
  for (const f of readdirSync(target).sort()) h.update(f).update(readFileSync(path.join(target, f)));
  return h.digest("hex");
};

afterAll(() => rmSync(target, { recursive: true, force: true }));

describe("scripts/sync-protocol.mjs", () => {
  it("--check fails on an empty target", () => {
    expect(run("--check").status).toBe(1);
  });

  it("vendors every src/*.ts with the header and nothing else", () => {
    expect(run().status).toBe(0);
    const src = readdirSync(path.join(PKG_ROOT, "src"))
      .filter((f) => f.endsWith(".ts"))
      .sort();
    expect(readdirSync(target).sort()).toEqual(src);
    for (const f of src) {
      expect(readFileSync(path.join(target, f), "utf8")).toBe(
        HEADER + readFileSync(path.join(PKG_ROOT, "src", f), "utf8"),
      );
    }
    expect(run("--check").status).toBe(0);
  });

  it("is deterministic (second run changes nothing)", () => {
    const before = digest();
    const second = run();
    expect(second.status).toBe(0);
    expect(second.stdout).toContain("0 changed");
    expect(digest()).toBe(before);
  });

  it("--check detects edits and stale files; a sync repairs them", () => {
    writeFileSync(path.join(target, "jcs.ts"), `${readFileSync(path.join(target, "jcs.ts"), "utf8")}// edit\n`);
    writeFileSync(path.join(target, "old.ts"), `${HEADER}export {};\n`);
    const check = run("--check");
    expect(check.status).toBe(1);
    expect(check.stderr).toContain("differs: jcs.ts");
    expect(check.stderr).toContain("stale: old.ts");
    expect(run().status).toBe(0);
    expect(run("--check").status).toBe(0);
  });

  it("refuses to delete a file it did not generate", () => {
    writeFileSync(path.join(target, "handwritten.ts"), "export const x = 1;\n");
    const r = run();
    expect(r.status).toBe(2);
    expect(r.stderr).toContain("refusing to delete");
    rmSync(path.join(target, "handwritten.ts"));
  });
});
